#!/usr/bin/env node
/**
 * generate-release-doc.js
 *
 * Single source of truth for docs/accounting-modernization/releases/CURRENT_RELEASE.md.
 * Reads docs/accounting-modernization/MODULE_STATE.json and deterministically
 * (re)generates the human-readable release summary from it, covering every
 * package and every story — not just the currently-active package — so the
 * file can never again go stale the way it did before R0 Stabilization Phase 1
 * (see docs/accounting-modernization/repository-verification/REPOSITORY_CONTRADICTIONS.md #1).
 *
 * Usage:
 *   node scripts/generate-release-doc.js          # regenerate the file
 *   node scripts/generate-release-doc.js --check  # exit 1 if the file on disk
 *                                                  # would differ from what
 *                                                  # MODULE_STATE.json implies
 */

'use strict';

const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..');
const STATE_PATH = path.join(REPO_ROOT, 'docs/accounting-modernization/MODULE_STATE.json');
const OUT_PATH = path.join(REPO_ROOT, 'docs/accounting-modernization/releases/CURRENT_RELEASE.md');

const STATUS_BADGE = {
  DONE: '✅ DONE',
  DONE_PENDING_INTEGRATION: '🟡 DONE_PENDING_INTEGRATION',
  IMPLEMENTED_UNVERIFIED: '🟠 IMPLEMENTED_UNVERIFIED',
  PARTIAL: '🟠 PARTIAL',
  BLOCKED: '🔴 BLOCKED',
  READY: '🔵 READY',
  NOT_STARTED: '⚪ NOT_STARTED',
};

function badge(status) {
  return STATUS_BADGE[status] || status;
}

function loadState() {
  const raw = fs.readFileSync(STATE_PATH, 'utf8');
  return JSON.parse(raw);
}

function storyTable(state, ids) {
  const rows = ids.map((id) => {
    const s = state.stories[id];
    if (!s) return `| ${id} | (not present in MODULE_STATE.json stories object) | — |`;
    return `| ${id} | ${s.title} | ${badge(s.status)} |`;
  });
  return ['| ID | Title | Status |', '|---|---|---|', ...rows].join('\n');
}

function generate(state) {
  const meta = state._meta || {};
  const allStoryIds = Object.keys(state.stories);
  const counts = allStoryIds.reduce((acc, id) => {
    const st = state.stories[id].status;
    acc[st] = (acc[st] || 0) + 1;
    return acc;
  }, {});
  const doneLike = (counts.DONE || 0) + (counts.DONE_PENDING_INTEGRATION || 0);

  const lines = [];
  lines.push('# Current Release — Human-Readable Summary');
  lines.push('<!-- AUTO-GENERATED from docs/accounting-modernization/MODULE_STATE.json -->');
  lines.push('<!-- Do NOT edit this file directly. Update MODULE_STATE.json, then run: -->');
  lines.push('<!--   node scripts/generate-release-doc.js -->');
  lines.push('<!-- CI must run `node scripts/generate-release-doc.js --check` and fail the build on drift. -->');
  lines.push('');
  lines.push('**Control file:** `docs/accounting-modernization/MODULE_STATE.json`');
  lines.push(`**Last updated:** ${meta.lastUpdated || 'unknown'}`);
  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push('## Active package');
  lines.push('');
  const pkg = state.package || {};
  lines.push(`**${pkg.id || state.activePackage}** — ${pkg.description || ''}`);
  lines.push('');

  lines.push('## All R0 stories currently tracked in MODULE_STATE.json');
  lines.push('');
  lines.push(`This table lists **every** story in MODULE_STATE.json's \`stories\` object (${allStoryIds.length} total), across every package — active and completed — so this file cannot silently omit a package the way it previously omitted R0-JOURNAL-LIFECYCLE.`);
  lines.push('');
  lines.push(storyTable(state, allStoryIds));
  lines.push('');
  lines.push(`**Totals:** ${JSON.stringify(counts)} — ${doneLike}/${allStoryIds.length} at DONE or DONE_PENDING_INTEGRATION.`);
  lines.push('');

  lines.push('## Completed packages');
  lines.push('');
  for (const p of state.completedPackages || []) {
    lines.push(`### ${p.id} — ${p.status}`);
    lines.push('');
    lines.push(`Closed: ${p.closedDate || 'n/a'}`);
    lines.push('');
    lines.push(storyTable(state, p.stories || []));
    lines.push('');
    lines.push(p.summary || '');
    lines.push('');
    if (Array.isArray(p.carryForwardIntegrations) && p.carryForwardIntegrations.length) {
      lines.push('Carry-forward integrations:');
      for (const c of p.carryForwardIntegrations) lines.push(`- ${c}`);
      lines.push('');
    }
  }

  lines.push('## Integration gate status');
  lines.push('');
  lines.push('(Verbatim from `MODULE_STATE.json.integrationGateStatus` — this is the authoritative list of what remains before any DONE_PENDING_INTEGRATION or PARTIAL story can become DONE.)');
  lines.push('');
  for (const [k, v] of Object.entries(state.integrationGateStatus || {})) {
    lines.push(`- **${k}**: ${v}`);
  }
  lines.push('');

  lines.push('## Binding decisions');
  lines.push('');
  lines.push('- Tenant is the dealer-group / security boundary only.');
  lines.push('- LegalEntity, Store, Franchise and Department are separate models.');
  lines.push('- Isolation: shared schema with application-layer tenantId scoping. **PostgreSQL RLS is NOT YET implemented** (see ADR-001 and `docs/accounting-modernization/repository-verification/TENANT_ISOLATION_VERIFICATION.md` — the previous version of this file incorrectly claimed RLS was already delivered; see `docs/accounting-modernization/stabilization/TENANT_ISOLATION_REPORT.md` for current status).');
  lines.push('- AuditPort/AuthzPort stubs permitted; stories using them are at most DONE_PENDING_INTEGRATION, never DONE.');
  lines.push('');

  lines.push('## Reference');
  lines.push('');
  lines.push('- Audit results: `docs/accounting-modernization/audit-results/`');
  lines.push('- Repository verification (baseline evidence): `docs/accounting-modernization/repository-verification/`');
  lines.push('- R0 stabilization reports: `docs/accounting-modernization/stabilization/`');
  lines.push('- Decision register: `docs/accounting-modernization/decisions/DECISION_REGISTER.md`');
  lines.push('- ADR-001 (Tenant Isolation): `docs/accounting-modernization/decisions/ADR-001_TENANT_ISOLATION.md`');
  lines.push('- Backlog package: `docs/accounting-modernization/AutoMate2_Accounting_Backlog_Package_v1.1.zip`');
  lines.push('');
  lines.push('---');
  lines.push('*This file is generated from MODULE_STATE.json by `scripts/generate-release-doc.js`. Do not hand-edit.*');
  lines.push('');

  return lines.join('\n');
}

function main() {
  const checkOnly = process.argv.includes('--check');
  const state = loadState();
  const generated = generate(state);

  if (checkOnly) {
    const onDisk = fs.existsSync(OUT_PATH) ? fs.readFileSync(OUT_PATH, 'utf8') : null;
    if (onDisk !== generated) {
      console.error('CURRENT_RELEASE.md is OUT OF SYNC with MODULE_STATE.json.');
      console.error(`Run: node scripts/generate-release-doc.js`);
      if (onDisk === null) {
        console.error(`(${OUT_PATH} does not exist)`);
      }
      process.exit(1);
    }
    console.log('CURRENT_RELEASE.md matches MODULE_STATE.json. OK.');
    process.exit(0);
  }

  fs.writeFileSync(OUT_PATH, generated, 'utf8');
  console.log(`Wrote ${path.relative(REPO_ROOT, OUT_PATH)}`);
}

main();
